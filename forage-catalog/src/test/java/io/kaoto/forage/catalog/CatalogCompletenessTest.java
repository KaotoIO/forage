package io.kaoto.forage.catalog;

import javax.xml.parsers.DocumentBuilderFactory;

import org.w3c.dom.Element;
import org.w3c.dom.NodeList;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import io.kaoto.forage.catalog.model.FactoryVariant;
import io.kaoto.forage.catalog.model.FactoryVariants;
import io.kaoto.forage.catalog.model.FeatureBeans;
import io.kaoto.forage.catalog.model.ForageBean;
import io.kaoto.forage.catalog.model.ForageCatalog;
import io.kaoto.forage.catalog.model.ForageFactory;
import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.ObjectMapper;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import static org.assertj.core.api.Assertions.assertThat;

/**
 * Verifies that every {@code @ForageBean} and {@code @ForageFactory} declared in the reactor sources ends up in the
 * generated {@code forage-catalog.json}, the only thing Kaoto and {@code camel forage run/export} know about.
 *
 * <p>The catalog plugin already fails on beans it scans but cannot attach to a factory. This test covers what the
 * plugin never sees: modules that are not dependencies of forage-catalog, and factory classes that do not make it
 * into a variant. Beans deliberately kept out of the catalog are listed, with a reason, in the
 * {@code <excludedBeans>} configuration of the forage-maven-catalog-plugin in this module's pom.xml.
 */
class CatalogCompletenessTest {

    private static final Set<String> SKIPPED_DIRECTORIES = Set.of("target", "node_modules");
    private static final Pattern PACKAGE = Pattern.compile("^package\\s+([\\w.]+)\\s*;", Pattern.MULTILINE);
    private static final Pattern ANNOTATED_CLASS = Pattern.compile(
            "^@(ForageBean|ForageFactory)\\b.*?^(?:public\\s+)?(?:(?:abstract|final)\\s+)*class\\s+(\\w+)",
            Pattern.MULTILINE | Pattern.DOTALL);

    private static Path moduleDir;
    private static List<Declaration> beans;
    private static List<Declaration> factories;
    private static Set<String> excludedBeans;
    private static ForageCatalog catalog;

    @BeforeAll
    static void scan() throws Exception {
        moduleDir = Path.of(System.getProperty("basedir", "")).toAbsolutePath();
        Path rootDir = moduleDir.getParent();
        assertThat(rootDir.resolve("pom.xml"))
                .as("reactor root of %s", moduleDir)
                .exists();

        List<Declaration> declarations = scanSources(rootDir);
        beans = declarations.stream().filter(d -> d.kind().equals("ForageBean")).toList();
        factories = declarations.stream()
                .filter(d -> d.kind().equals("ForageFactory"))
                .toList();
        // Guard against a scan that silently finds nothing (wrong root, changed layout)
        assertThat(beans).extracting(Declaration::className).contains("io.kaoto.forage.jdbc.postgresql.PostgresqlJdbc");
        assertThat(factories).extracting(Declaration::className).contains("io.kaoto.forage.jdbc.DataSourceBeanFactory");

        excludedBeans = readExcludedBeans(moduleDir.resolve("pom.xml"));

        Path catalogFile = moduleDir.resolve("target/generated-catalog/forage-catalog.json");
        assertThat(catalogFile)
                .as("generated by forage-maven-catalog-plugin in the process-classes phase")
                .exists();
        catalog = new ObjectMapper()
                .configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false)
                .readValue(catalogFile.toFile(), ForageCatalog.class);
    }

    @Test
    void everyForageBeanIsInTheCatalogOrExcluded() {
        Set<String> catalogBeans = catalogBeanClassNames();

        List<String> missing = beans.stream()
                .filter(bean -> !catalogBeans.contains(bean.className()))
                .filter(bean -> !excludedBeans.contains(bean.className()))
                .map(CatalogCompletenessTest::describeMissing)
                .toList();

        assertThat(missing)
                .as("@ForageBean classes missing from forage-catalog.json. Add the module as a dependency of "
                        + "forage-catalog, give the bean a component that a @ForageFactory declares, or add it to "
                        + "<excludedBeans> in forage-catalog/pom.xml with a reason")
                .isEmpty();
    }

    @Test
    void excludedBeansAreDeclaredAndNotInTheCatalog() {
        Set<String> declaredBeans = beans.stream().map(Declaration::className).collect(Collectors.toSet());
        Set<String> catalogBeans = catalogBeanClassNames();

        assertThat(excludedBeans)
                .as("<excludedBeans> entries in forage-catalog/pom.xml that are not @ForageBean classes")
                .isSubsetOf(declaredBeans);
        assertThat(excludedBeans)
                .as("<excludedBeans> entries in forage-catalog/pom.xml that are in the catalog: remove them")
                .doesNotContainAnyElementsOf(catalogBeans);
    }

    @Test
    void everyForageFactoryIsInTheCatalog() {
        Set<String> catalogFactories = catalog.getFactories().stream()
                .map(ForageFactory::getVariants)
                .filter(Objects::nonNull)
                .flatMap(CatalogCompletenessTest::variants)
                .map(FactoryVariant::getClassName)
                .collect(Collectors.toSet());

        List<String> missing = factories.stream()
                .filter(factory -> !catalogFactories.contains(factory.className()))
                .map(CatalogCompletenessTest::describeMissing)
                .toList();

        assertThat(missing)
                .as("@ForageFactory classes missing from the variants of forage-catalog.json. Add the module as a "
                        + "dependency of forage-catalog, and give each variant of a factory type its own class")
                .isEmpty();
    }

    @Test
    void everyFactoryWithComponentsHasBeans() {
        // A factory that creates its bean itself, like TLS Context, declares no components and lists no beans
        List<String> empty = catalog.getFactories().stream()
                .filter(factory -> factory.getComponents() != null
                        && !factory.getComponents().isEmpty())
                .filter(factory -> beansOf(factory).findAny().isEmpty())
                .map(factory -> factory.getName() + " " + factory.getComponents())
                .toList();

        assertThat(empty)
                .as("factories that declare components but list no bean, so Kaoto offers nothing to select. Add the "
                        + "provider modules as dependencies of forage-catalog, or declare no components if the "
                        + "factory creates its bean itself")
                .isEmpty();
    }

    private static Set<String> catalogBeanClassNames() {
        return catalog.getFactories().stream()
                .flatMap(CatalogCompletenessTest::beansOf)
                .map(ForageBean::getClassName)
                .collect(Collectors.toSet());
    }

    private static Stream<ForageBean> beansOf(ForageFactory factory) {
        if (factory.getBeansByFeature() == null) {
            return Stream.empty();
        }
        return factory.getBeansByFeature().stream()
                .map(FeatureBeans::getBeans)
                .filter(Objects::nonNull)
                .flatMap(List::stream);
    }

    private static Stream<FactoryVariant> variants(FactoryVariants variants) {
        return Stream.of(variants.getBase(), variants.getSpringboot(), variants.getQuarkus())
                .filter(Objects::nonNull);
    }

    private static String describeMissing(Declaration declaration) {
        String reason = isOnClasspath(declaration.className())
                ? "on the forage-catalog classpath but not in the catalog, check the forage-maven-catalog-plugin log"
                : "its module is not a dependency of forage-catalog";
        return "%s (%s): %s".formatted(declaration.className(), declaration.module(), reason);
    }

    private static boolean isOnClasspath(String className) {
        try {
            Class.forName(className, false, CatalogCompletenessTest.class.getClassLoader());
            return true;
        } catch (ClassNotFoundException | LinkageError e) {
            return false;
        }
    }

    /**
     * Finds the top-level classes annotated with {@code @ForageBean} or {@code @ForageFactory} in every
     * {@code src/main/java} directory below the reactor root.
     */
    private static List<Declaration> scanSources(Path rootDir) throws IOException {
        List<Declaration> declarations = new ArrayList<>();
        Files.walkFileTree(rootDir, new SimpleFileVisitor<>() {
            @Override
            public FileVisitResult preVisitDirectory(Path dir, BasicFileAttributes attrs) {
                String name = dir.getFileName().toString();
                // Hidden directories may hold copies of the repository, such as git worktrees
                if (!dir.equals(rootDir) && (name.startsWith(".") || SKIPPED_DIRECTORIES.contains(name))) {
                    return FileVisitResult.SKIP_SUBTREE;
                }
                return FileVisitResult.CONTINUE;
            }

            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws IOException {
                String path = rootDir.relativize(file).toString().replace('\\', '/');
                int sourceRoot = path.indexOf("/src/main/java/");
                if (sourceRoot > 0 && path.endsWith(".java")) {
                    String source = Files.readString(file);
                    Matcher packageMatcher = PACKAGE.matcher(source);
                    String packagePrefix = packageMatcher.find() ? packageMatcher.group(1) + "." : "";
                    Matcher annotated = ANNOTATED_CLASS.matcher(source);
                    while (annotated.find()) {
                        declarations.add(new Declaration(
                                annotated.group(1), packagePrefix + annotated.group(2), path.substring(0, sourceRoot)));
                    }
                }
                return FileVisitResult.CONTINUE;
            }
        });
        return declarations;
    }

    private static Set<String> readExcludedBeans(Path pom) throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        NodeList entries = factory.newDocumentBuilder().parse(pom.toFile()).getElementsByTagName("excludedBean");
        Set<String> classNames = new HashSet<>();
        for (int i = 0; i < entries.getLength(); i++) {
            NodeList className = ((Element) entries.item(i)).getElementsByTagName("className");
            if (className.getLength() > 0) {
                classNames.add(className.item(0).getTextContent().trim());
            }
        }
        return classNames;
    }

    private record Declaration(String kind, String className, String module) {}
}
