package io.kaoto.forage.config.editor;

import java.io.File;
import java.nio.file.Files;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import io.kaoto.forage.catalog.reader.ForageCatalogReader;
import io.kaoto.forage.config.editor.ForageConfigurationEditor.ConfigurationEditException;
import io.kaoto.forage.config.editor.ForageConfigurationEditor.EditResult;
import io.kaoto.forage.config.editor.ForageConfigurationEditor.FileChange;
import io.kaoto.forage.config.editor.PropertiesDocument.TextEdit;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class ForageConfigurationEditorTest {

    private static final ForageCatalogReader CATALOG = ForageCatalogReader.getInstance();

    @TempDir
    File tempDir;

    @Test
    void writeCreatesTheFileWithAHeader() throws Exception {
        EditResult result = editor(PropertiesFileStrategyType.APPLICATION)
                .write("jdbc", "ds1", properties("jdbc.db.kind", "postgresql", "forage.jdbc.url", "jdbc:h2:mem:x"));

        FileChange change = result.changes().get(0);
        assertThat(change.created()).isTrue();
        assertThat(change.edits()).containsExactly(new TextEdit(0, 0, change.lines()));
        result.write();

        assertThat(read("application.properties"))
                .isEqualTo(
                        """
                        # Forage DataSource Configuration
                        # Generated by Forage JBang Plugin

                        forage.ds1.jdbc.db.kind=postgresql
                        forage.ds1.jdbc.url=jdbc:h2:mem:x
                        """);
    }

    @Test
    void writeUpdatesInPlaceWithTextEdits() throws Exception {
        write("application.properties", "# app", "forage.ds1.jdbc.url=old", "camel.main.name=app");

        EditResult result = editor(PropertiesFileStrategyType.APPLICATION)
                .write("jdbc", "ds1", properties("jdbc.url", "new", "jdbc.username", "sa"));

        assertThat(result.changes().get(0).edits())
                .containsExactly(
                        new TextEdit(1, 2, List.of("forage.ds1.jdbc.url=new")),
                        new TextEdit(3, 3, List.of("forage.ds1.jdbc.username=sa")));
        result.write();
        assertThat(read("application.properties"))
                .isEqualTo("# app\nforage.ds1.jdbc.url=new\ncamel.main.name=app\nforage.ds1.jdbc.username=sa\n");
    }

    @ParameterizedTest
    @ValueSource(strings = {"ollama", "Azure", "jdbc", "google", "multi", "my.ds", "my ds", "-x", ""})
    void newInstancesNeedAnUnambiguousName(String name) {
        ForageConfigurationEditor editor = editor(PropertiesFileStrategyType.APPLICATION);

        assertThat(editor.validateNewInstanceName(name)).isPresent();
        assertThatThrownBy(() -> editor.write("jdbc", name, properties("jdbc.db.kind", "h2")))
                .isInstanceOf(ConfigurationEditException.class);
        assertThat(new File(tempDir, "application.properties")).doesNotExist();
    }

    @ParameterizedTest
    @ValueSource(strings = {"ds1", "myPG", "my-db", "orders_db", "h2", "postgresql", "test"})
    void validInstanceNames(String name) {
        assertThat(editor(PropertiesFileStrategyType.APPLICATION).validateNewInstanceName(name))
                .isEmpty();
    }

    @Test
    void existingInstancesWithAnAmbiguousNameCanBeUpdated() throws Exception {
        write("application.properties", "forage.ollama.jdbc.db.kind=h2");

        editor(PropertiesFileStrategyType.APPLICATION)
                .write("jdbc", "ollama", properties("jdbc.url", "jdbc:h2:mem:x"))
                .write();

        assertThat(read("application.properties"))
                .isEqualTo("forage.ollama.jdbc.db.kind=h2\nforage.ollama.jdbc.url=jdbc:h2:mem:x\n");
    }

    @Test
    void forageStrategyWritesBeanPropertiesToTheBeanFile() throws Exception {
        // Bedrock declares its own properties file, the agent factory has another one
        EditResult result = editor(PropertiesFileStrategyType.FORAGE)
                .write("agent", "a1", properties("agent.model.kind", "bedrock", "bedrock.region", "eu-west-1"));

        assertThat(result.changes())
                .extracting(change -> change.file().getName())
                .containsExactlyInAnyOrder("forage-agent-factory.properties", "forage-model-bedrock.properties");
        assertThat(result.warnings()).isEmpty();
    }

    @Test
    void forageStrategyWarnsWhenTheBeanFileIsUnknown() throws Exception {
        EditResult result = editor(PropertiesFileStrategyType.FORAGE)
                .write("agent", "a1", properties("ollama.model.name", "llama3"));

        assertThat(result.changes())
                .extracting(change -> change.file().getName())
                .containsExactly("forage-agent-factory.properties");
        assertThat(result.warnings()).singleElement().asString().contains("ollama", "application.properties");

        // Factory properties, and the application strategy, need no warning
        assertThat(editor(PropertiesFileStrategyType.FORAGE)
                        .write("jdbc", "ds1", properties("jdbc.url", "x"))
                        .warnings())
                .isEmpty();
        assertThat(editor(PropertiesFileStrategyType.APPLICATION)
                        .write("agent", "a1", properties("ollama.model.name", "llama3"))
                        .warnings())
                .isEmpty();
    }

    @Test
    void forageStrategyRejectsFactoriesWithoutAFile() {
        assertThatThrownBy(() -> editor(PropertiesFileStrategyType.FORAGE)
                        .write("tavily", null, properties("tavily.api.key", "k")))
                .isInstanceOf(ConfigurationEditException.class)
                .hasMessageContaining("WebSearch has no dedicated properties file");
    }

    @Test
    void deleteRemovesTheInstanceAndItsReferences() throws Exception {
        write(
                "application.properties",
                "forage.multi.agent.names=a1,a2",
                "forage.a1.agent.model.kind=ollama",
                "forage.a2.agent.model.kind=ollama");
        ForageConfigurationEditor editor = editor(PropertiesFileStrategyType.APPLICATION);

        EditResult result = editor.delete("a1");

        FileChange change = result.changes().get(0);
        assertThat(change.removedEntries()).isEqualTo(1);
        assertThat(change.writtenEntries()).isEqualTo(1);
        assertThat(change.edits())
                .containsExactly(
                        new TextEdit(0, 1, List.of("forage.multi.agent.names=a2")), new TextEdit(1, 2, List.of()));
        result.write();
        assertThat(read("application.properties"))
                .isEqualTo("forage.multi.agent.names=a2\nforage.a2.agent.model.kind=ollama\n");

        // The last name removes the list
        editor.delete("a2").write();
        assertThat(read("application.properties")).isEmpty();
    }

    @Test
    void deleteOfAnUnknownInstanceFails() throws Exception {
        write("application.properties", "forage.ds1.jdbc.url=x");

        assertThatThrownBy(() -> editor(PropertiesFileStrategyType.APPLICATION).delete("ds2"))
                .isInstanceOf(ConfigurationEditException.class)
                .hasMessage("No configuration found for instance 'ds2'");
    }

    @Test
    void deleteUnderTheApplicationStrategyIncludesProfileFiles() throws Exception {
        write("application.properties", "forage.ds1.jdbc.url=x");
        write("application-dev.properties", "forage.ds1.jdbc.url=y", "camel.main.name=dev");
        write("forage-datasource-factory.properties", "forage.ds1.jdbc.url=z");

        EditResult result = editor(PropertiesFileStrategyType.APPLICATION).delete("ds1");

        assertThat(result.changes())
                .extracting(change -> change.file().getName())
                .containsExactly("application.properties", "application-dev.properties");
    }

    @Test
    void removeStoredForageDependencies() throws Exception {
        write(
                "application.properties",
                "camel.jbang.dependencies=com.example:lib:1.0,io.kaoto.forage:forage-jdbc-postgresql:1.0.0",
                "camel.jbang.dependencies.main=mvn:io.kaoto.forage:forage-jdbc:1.0.0");

        EditResult result = editor(PropertiesFileStrategyType.FORAGE).removeStoredForageDependencies();

        assertThat(result.removedDependencies())
                .containsExactly(
                        "io.kaoto.forage:forage-jdbc-postgresql:1.0.0", "mvn:io.kaoto.forage:forage-jdbc:1.0.0");
        result.write();
        assertThat(read("application.properties")).isEqualTo("camel.jbang.dependencies=com.example:lib:1.0\n");
        assertThat(editor(PropertiesFileStrategyType.FORAGE)
                        .removeStoredForageDependencies()
                        .changes())
                .isEmpty();
    }

    @Test
    void readUsesTheStrategyFiles() throws Exception {
        write("application.properties", "forage.appDs.jdbc.url=x");
        write("forage-datasource-factory.properties", "forage.forageDs.jdbc.url=y");

        assertThat(editor(PropertiesFileStrategyType.FORAGE).read().instances())
                .extracting(ForageConfiguration.Instance::name)
                .containsExactly("forageDs");
    }

    private ForageConfigurationEditor editor(PropertiesFileStrategyType type) {
        return new ForageConfigurationEditor(CATALOG, tempDir, type.create(CATALOG));
    }

    private static Map<String, String> properties(String... keyValues) {
        Map<String, String> properties = new LinkedHashMap<>();
        for (int i = 0; i < keyValues.length; i += 2) {
            properties.put(keyValues[i], keyValues[i + 1]);
        }
        return properties;
    }

    private void write(String name, String... lines) throws Exception {
        Files.writeString(new File(tempDir, name).toPath(), String.join("\n", lines) + "\n");
    }

    private String read(String name) throws Exception {
        return Files.readString(new File(tempDir, name).toPath());
    }
}
